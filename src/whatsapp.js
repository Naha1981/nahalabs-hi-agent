// WhatsApp connector. Engine-agnostic: inbound arrives at /internal/wa/inbound (shared secret), replies go through an adapter.
// Rules: reply-only to saved contacts who messaged first; unknown senders are logged and ignored; no outbound-first messages;
// per-contact and per-tenant caps; paused tenant or emergency stop silences it.
import { withTenant, withSystem, audit } from './db.js';
import { createHash, timingSafeEqual } from 'node:crypto';
import { runAgent } from './agent.js';
import { emergencyStopped } from './core.js';

export const normalisePhone = (p) => String(p || '').replace(/[^0-9]/g, '').replace(/^0(\d{9})$/, '27$1');

export async function handleInbound({ to, from, text, externalId, llm, fetchImpl, lookup, adapter }) {
  const toN = normalisePhone(to), fromN = normalisePhone(from);
  if (!/^[0-9]{8,15}$/.test(toN) || !/^[0-9]{8,15}$/.test(fromN)) return { status: 400, reason: 'bad number' };
  if (await emergencyStopped()) return { status: 200, ignored: 'emergency stop' };
  const ch = (await withSystem((c) => c.query('SELECT * FROM wa_channel_lookup($1)', [toN]))).rows[0];
  if (!ch) return { status: 200, ignored: 'no active channel' };
  const tenantId = ch.tenant_id;
  const channel = (await withTenant(tenantId, (c) => c.query("SELECT * FROM wa_channels WHERE number=$1 AND status='active'", [toN]))).rows[0];
  if (!channel) return { status: 200, ignored: 'no active channel' };
  const body = String(text || '').slice(0, 2000).trim();

  // Owner verification is a one-time challenge generated from the signed-in HI WhatsApp page.
  // The code is hashed in storage, expires after ten minutes, is single-use, and is never saved
  // in the message log. Until verified, the configured owner number receives no owner privileges.
  const verificationMatch = body.match(/^HI\s+VERIFY\s+([0-9]{6})$/i);
  if (verificationMatch) {
    const outcome = await withTenant(tenantId, async (c) => {
      const current = (await c.query('SELECT * FROM wa_channels WHERE id=$1 FOR UPDATE', [channel.id])).rows[0];
      if (!current || current.owner_phone !== fromN || !current.owner_verification_hash) {
        return { ok: false, reason: 'no pending verification for this number' };
      }
      if (Number(current.owner_verification_attempts || 0) >= 5) {
        await c.query('UPDATE wa_channels SET owner_verification_hash=NULL, owner_verification_expires_at=NULL WHERE id=$1', [channel.id]);
        return { ok: false, reason: 'attempt limit reached; generate a new code' };
      }
      const expires = current.owner_verification_expires_at ? new Date(current.owner_verification_expires_at).getTime() : 0;
      if (!Number.isFinite(expires) || expires <= Date.now()) {
        await c.query('UPDATE wa_channels SET owner_verification_hash=NULL, owner_verification_expires_at=NULL WHERE id=$1', [channel.id]);
        await audit(c, tenantId, 'system', 'wa.owner_verification_expired', { channel_id: channel.id });
        return { ok: false, reason: 'code expired; generate a new code' };
      }
      const expected = Buffer.from(String(current.owner_verification_hash), 'utf8');
      const supplied = Buffer.from(createHash('sha256').update(verificationMatch[1]).digest('hex'), 'utf8');
      const matches = expected.length === supplied.length && expected.length > 0 && timingSafeEqual(expected, supplied);
      if (!matches) {
        const attempts = Number(current.owner_verification_attempts || 0) + 1;
        await c.query(
          "UPDATE wa_channels SET owner_verification_attempts=$2, owner_verification_hash=CASE WHEN $2 >= 5 THEN NULL ELSE owner_verification_hash END, owner_verification_expires_at=CASE WHEN $2 >= 5 THEN NULL ELSE owner_verification_expires_at END WHERE id=$1",
          [channel.id, attempts]);
        await audit(c, tenantId, 'system', 'wa.owner_verification_failed', { channel_id: channel.id, attempts });
        return { ok: false, reason: attempts >= 5 ? 'attempt limit reached; generate a new code' : 'incorrect code' };
      }
      await c.query(
        'UPDATE wa_channels SET owner_verified_at=now(), owner_verification_hash=NULL, owner_verification_expires_at=NULL, owner_verification_attempts=0 WHERE id=$1',
        [channel.id]);
      await audit(c, tenantId, 'system', 'wa.owner_verified', { channel_id: channel.id });
      return { ok: true };
    });
    if (!outcome.ok) return { status: 200, ignored: 'owner verification ' + outcome.reason };
    // This fixed confirmation is a deliberately whitelisted system acknowledgement, not model output.
    // All later generated replies, including owner-directed replies, still require HI approval.
    if (adapter) {
      try {
        await adapter({
          engine: channel.engine, from: toN, to: fromN,
          text: 'HI: your owner number is verified. Replies generated by HI remain in the Approval queue until you approve them.'
        });
      } catch {}
    }
    return { status: 200, owner_verified: true };
  }

  const isOwner = Boolean(channel.owner_verified_at && channel.owner_phone === fromN);
  if (!isOwner && channel.owner_phone === fromN) {
    await withTenant(tenantId, async (c) => {
      await c.query(
        "INSERT INTO wa_messages (tenant_id, phone, direction, body, status, external_id) VALUES (current_setting('app.tenant_id')::uuid,$1,'in',$2,'ignored',$3)",
        [fromN, 'Owner number not verified; message withheld.', externalId || null]);
      await audit(c, tenantId, 'system', 'wa.unverified_owner_ignored', { channel_id: channel.id });
    });
    return { status: 200, ignored: 'owner number not verified' };
  }

  const gate = await withTenant(tenantId, async (c) => {
    if (externalId && (await c.query('SELECT 1 FROM wa_messages WHERE external_id=$1', [externalId])).rowCount) return { dup: true };
    const contact = isOwner ? null : (await c.query('SELECT * FROM wa_contacts WHERE phone=$1', [fromN])).rows[0];
    if (!isOwner && !contact) {
      await c.query("INSERT INTO wa_messages (tenant_id, phone, direction, body, status, external_id) VALUES (current_setting('app.tenant_id')::uuid,$1,'in',$2,'ignored',$3)", [fromN, body.slice(0, 200), externalId || null]);
      await audit(c, tenantId, 'system', 'wa.ignored_unknown_sender', {});
      return { ignored: 'sender is not a saved contact' };
    }
    const recent = (await c.query("SELECT count(*)::int n FROM wa_messages WHERE phone=$1 AND direction='in' AND status<>'ignored' AND created_at > now() - interval '1 hour'", [fromN])).rows[0].n;
    const daily = (await c.query("SELECT count(*)::int n FROM wa_messages WHERE direction='out' AND status IN ('queued','sent') AND created_at > now() - interval '1 day'")).rows[0].n;
    if (recent >= 20 || daily >= Number(process.env.WA_MAX_REPLIES_PER_TENANT_DAY || 100)) return { ignored: 'rate limit' };
    await c.query("INSERT INTO wa_messages (tenant_id, phone, direction, body, status, external_id) VALUES (current_setting('app.tenant_id')::uuid,$1,'in',$2,'received',$3)", [fromN, body, externalId || null]);
    const prev = (await c.query("SELECT conversation_id FROM wa_messages WHERE phone=$1 AND conversation_id IS NOT NULL AND created_at > now() - interval '12 hours' ORDER BY id DESC LIMIT 1", [fromN])).rows[0];
    const owner = (await c.query("SELECT email FROM users WHERE tenant_id=current_setting('app.tenant_id')::uuid ORDER BY created_at LIMIT 1")).rows[0];
    return { contact, body, conversationId: prev?.conversation_id || null, email: owner?.email, isOwner };
  });
  if (gate.dup) return { status: 200, ignored: 'duplicate' };
  if (gate.ignored) return { status: 200, ignored: gate.ignored };
  const senderLabel = gate.isOwner ? 'the verified account owner' : (gate.contact?.name || 'a saved contact');
  const r = await runAgent({
    tenantId, userEmail: gate.email, agentId: ch.agent_id, conversationId: gate.conversationId,
    userText: 'WhatsApp message from ' + senderLabel + ': ' + gate.body,
    llm, fetchImpl, lookup, principal: gate.isOwner ? 'owner' : 'external_contact'
  });
  if (r.error) return { status: 200, ignored: r.error };
  const reply = String(r.answer).replace(/\*\*/g, '*').slice(0, 1500);
  const queued = await withTenant(tenantId, async (c) => {
    const msg = (await c.query(
      "INSERT INTO wa_messages (tenant_id, phone, direction, body, status, conversation_id) VALUES (current_setting('app.tenant_id')::uuid,$1,'out',$2,'queued',$3) RETURNING id",
      [fromN, reply, r.conversationId || gate.conversationId]
    )).rows[0];
    const approval = (await c.query(
      "INSERT INTO approvals (tenant_id, kind, summary, payload, proposed_by) VALUES (current_setting('app.tenant_id')::uuid,'wa_reply',$1,$2,'agent:whatsapp') RETURNING id",
      ['WhatsApp reply to ' + senderLabel + ' (' + fromN + ')', JSON.stringify({
        channel_id: channel.id, wa_message_id: String(msg.id), to_phone: fromN, body: reply
      })]
    )).rows[0];
    await audit(c, tenantId, 'agent:whatsapp', 'wa.reply_proposed', { approval_id: approval.id, message_id: String(msg.id) });
    return { approvalId: approval.id };
  });
  // No generated WhatsApp reply is sent here. Sending is performed only by decideApproval.
  return { status: 200, queued: true, replied: false, delivery: 'awaiting_approval', approval_id: queued.approvalId, reply };
}

// Default adapter. The simulator keeps replies in wa_messages only. A real engine plugs in here once a number is linked.
export function makeAdapter(fetchImpl = fetch) {
  return async ({ engine, from, to, text }) => {
    if (engine === 'simulator') return;
    if (engine === 'own_engine') {
      const url = process.env.WA_ENGINE_URL, key = process.env.WA_ENGINE_KEY;
      if (!url || !key) throw new Error('engine not configured');
      const res = await fetchImpl(url, { method: 'POST', headers: { 'content-type': 'application/json', authorization: `Bearer ${key}` }, body: JSON.stringify({ from, to, text }), signal: AbortSignal.timeout(15000) });
      if (!res.ok) throw new Error('engine http ' + res.status);
      return;
    }
    if (engine === 'meta_cloud') {
      // Official WhatsApp Business Platform (Meta Cloud API). Text replies only; no templates here.
      const phoneId = process.env.WA_META_PHONE_NUMBER_ID, token = process.env.WA_META_TOKEN;
      if (!phoneId || !token) throw new Error('meta_cloud not configured');
      const res = await fetchImpl(`https://graph.facebook.com/v21.0/${phoneId}/messages`, {
        method: 'POST',
        headers: { 'content-type': 'application/json', authorization: `Bearer ${token}` },
        body: JSON.stringify({ messaging_product: 'whatsapp', to, type: 'text', text: { body: text.slice(0, 4000) } }),
        signal: AbortSignal.timeout(15000),
      });
      if (!res.ok) throw new Error('meta_cloud http ' + res.status);
      return;
    }
    throw new Error('engine not supported yet');
  };
}

// Parse a Meta Cloud API webhook payload into our inbound shape. Only text messages;
// everything else (statuses, reactions, media) is skipped. to = our WABA display number.
export function parseMetaWebhook(payload) {
  const out = [];
  for (const entry of payload?.entry || []) {
    for (const change of entry?.changes || []) {
      const v = change?.value || {};
      const to = String(v?.metadata?.display_phone_number || '');
      for (const m of v?.messages || []) {
        if (m?.type !== 'text') continue;
        out.push({ to, from: String(m.from || ''), text: String(m.text?.body || ''), externalId: m.id ? String(m.id).slice(0, 80) : null });
      }
    }
  }
  return out;
}
